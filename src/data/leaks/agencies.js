// Build a frozen item: `sources` is a list of S keys; `scale.from` names which of them states the number.
function item(o) {
  const keys = o.sources;
  const out = { ...o, sources: Object.freeze(keys.map((k) => {
    if (!S[k]) throw new Error(`agencies.js: unknown source ${k}`);
    return Object.freeze({ ...S[k] });
  })) };
  if (o.scale) {
    const { from, ...rest } = o.scale;
    const idx = keys.indexOf(from);
    if (idx < 0) throw new Error(`agencies.js: scale source ${from} not in ${o.id}'s sources`);
    out.scale = Object.freeze({ ...rest, source: idx });
  }
  for (const k of ['authority', 'partners']) if (Array.isArray(out[k])) out[k] = Object.freeze([...out[k]]);
  return Object.freeze(out);
}

